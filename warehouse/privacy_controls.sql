CREATE ROLE IF NOT EXISTS HEALTHCARE_REPORT_READER;
GRANT USAGE ON DATABASE HEALTHCARE_POPULATION TO ROLE HEALTHCARE_REPORT_READER;
GRANT USAGE ON SCHEMA HEALTHCARE_POPULATION.ANALYTICS_REPORTING TO ROLE HEALTHCARE_REPORT_READER;
-- Grant only aggregate reports, not member-level care gaps or high-cost records.
GRANT SELECT ON TABLE HEALTHCARE_POPULATION.ANALYTICS_REPORTING.RPT_COST_PMPM TO ROLE HEALTHCARE_REPORT_READER;
CREATE MASKING POLICY IF NOT EXISTS HEALTHCARE_POPULATION.ANALYTICS.MEMBER_MASK
 AS (val STRING) RETURNS STRING -> CASE WHEN CURRENT_ROLE()='SYSADMIN' THEN val ELSE 'MASKED' END;
